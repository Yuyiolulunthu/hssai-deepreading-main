2. 多視角時，各層分析可並行展開；不同視角對同一層的歧異判定本身即有分析價值
3. 使用者指定單一視角時，僅用該視角

社會學視角有一項貫穿性要求：知識社會學的自反性（reflexivity）——
同時追問『這個研究說了什麼』與『這個研究的存在本身說明了什麼』。

若分析對象本身已是一篇評論、詮釋或研究（而非小說、史著、哲學原典等
一階創作），須先辨識這是二階文本——它的『情節』是評論者對其所評論的
文本／作者所做的敘事賦形，它的『論證』證成邏輯是詮釋學式的（文本涵蓋
度、部分與整體的融貫、慷慨原則的邊界），而非命題邏輯式的。分析二階
文本時，須在文本定位處聲明：AI 是否讀過該評論所依據的一階原典；若未
讀過，所有涉及『評論是否貼合原著』的判斷，一律標記為對評論內部融貫
性的檢驗，而非對照原著的獨立裁決。

