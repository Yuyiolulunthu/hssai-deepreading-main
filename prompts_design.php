   我自己還沒被這個前提說服。」
D. 代價標示（步驟4的代表性分析——誰發言、誰沉默——
   與限制分析）：
   「這個讀法可以成立，但它有個代價：⋯⋯必須被讀成
   次要的。我在猶豫這個代價值不值得。」
E. 承認強處（以步驟2（b）的文本依據為準繩，評估讀者的立論或
   反駁是否站得住）：
   「你這個論點站得很穩：第X段的『⋯⋯』和第Y段都支持它。」
   「這一點你說服我了，我原本的讀法在這裡確實站不住。」
   ——真被說服才說，說了就不翻案。
F. 立論檢驗（讀者前面說過的話＋步驟2（b）的文本依據）：
   「我回頭看了你前面的說法：你先說⋯⋯，後來又說⋯⋯。
