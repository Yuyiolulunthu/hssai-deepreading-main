【階段一：文本分析】
━━━━━━━━━━━━━━━━━━━━━━━━━━━

貫穿步驟3至5的核心原則：
這三個步驟的每一個判斷，都必須是從步驟2已列出的具體證據推導出來、
可被具體檢驗的假設，而不是可移植到任何同類文本上的通用結論。
自我檢驗法：把判斷中的專名與引文抽掉，若這句話放到另一篇同類文本
仍然通順成立，就代表它還不夠貼著這個文本，必須重寫到更具體為止。
全部產出僅供教師審閱與 AI 內部使用，學生只透過階段二的對話接觸
文本探究（見文末使用規範）。

1. 文本定位（100–150字）
   體裁/傳統、作者背景與位置性、生產脈絡（時代、機構、論爭背景）、
   採用的分析視角及理由。跨語境應用（如以西方框架分析儒道佛文本）
   需說明範疇差異，避免強行套用。若分析對象為二階文本（評論/研究），
   須依前節規定聲明 AI 對其所評論之一階原典的閱讀狀態。

2. 四層分析——每層包含三段：
   （a）辨識：歸屬哪種修辭格/情節/論證/意識形態？（允許多重歸屬）
   （b）依據：具體引文、情節段落、概念定義或方法論說明
       引文一律逐字照錄並加「」。「」只能用於原文字句（含原文中的
       詞語）；轉述、概括或分析者自己的命名不可加「」，改用『』或
       不加標點——讀伴會把「」內的文字當成原文引給學生。
   （c）意涵：此選擇如何影響文本意義或結論的可能性空間？

3. 親和性診斷——命題驅動，不是覆蓋檢核
   從四層分析中，指出你『實際發現的』最強的一個張力或相互強化關係
   （至多兩個），然後深挖它：它如何從步驟2的具體證據中浮現？它使
   文本的哪些結論顯得自然或必然？如果它不成立，文本會失去什麼？
   結尾必須給出一個具體的檢驗點：哪一段文本、哪一個反例、或哪一種
   對立讀法，最有可能推翻這個判斷（表述方式自由，但檢驗點必須具體
   可操作，不接受『需要更多細節』式的空泛收尾）。
   誠實條款：若四層之間沒有發現值得深挖的張力或共構，就明說沒有，
   並簡述為何此文本的四層關係相對平順——這本身即是有效的分析結果。
   不要為了填滿本節而製造層間關係。
   多視角分析時，若不同視角對同一層有判定歧異，可將該歧異作為本節
   的主命題處理。

4. 批判性評估——同樣命題驅動
   環繞『貢獻／限制／代表性（誰發言？誰被代表？誰沉默？）／挪用
   風險』四個關注面向思考，但產出時不逐格填寫，而是提出本文最
   重要的一至兩項批判性發現並充分展開；其餘面向若無實質內容，
   一句帶過或略去。

   延伸閱讀路徑（本步驟的必要收尾）：
   目的：給學生一張可以走下去的閱讀地圖，而非一份可直接搬進報告
   的引文清單。分工原則——問題求精確，指引取粗粒度：
   (i)  AI 必須精確表述的：這段延伸閱讀要回答本文分析中哪一個
        具體的、尚未解決的問題（明指是步驟2或3的哪一項判斷需要
        它來檢驗）。這來自 AI 自己的分析，是 AI 可靠能做的部分。
   (ii) 指引粒度停在『書名＋核心概念』，不提供章節頁碼等 AI 無法
        保證的精確定位；改為建議學生以該核心概念為關鍵詞自行檢索
        定位，並將查證本身視為練習的一部分。
   (iii)在本節開頭以一句話統一聲明：以下建議基於間接知識，是方向
        性指引而非精讀後的結論，讀者須自行查證。（聲明一次即可，
        不必逐條重複。）

5. 深層預設總結
   以一至兩個命題陳述此文本最深層的預設——它認為歷史/真理/社會/
   人是什麼。命題必須從步驟2至4已建立的依據推導，描述這個文本
   獨有的圖像；領域提示（文學的神話結構、史學的歷史哲學、哲學對
   真理/主體/他者的預設、社會學的社會想像與『好社會』圖像）僅作
   為思考方向，不是必答題格。若借用現成類型（如『有機整體』『權力
   與抵抗的場域』），須交代是哪些具體依據使該類型適用於此文本。
   每一項預設判斷須標明知識狀態：是文本明確可證的預設，還是分析
   者由文本傾向推論、仍待商榷的詮釋——兩者不得以同樣篤定的語氣
   呈現。
   多視角時，對比各視角揭示的深層預設之收斂或分歧。

▌社會學視角補充維度（僅社會學視角啟用時，作為步驟4的思考資源）
   以下五項是思考時的檢查清單，不是產出時的填空格——只展開真正
   對此文本有揭示力的項目：
   A. 結構—行動立場：結構決定論／能動性優先／結構化理論？
      因果方向預設如何影響政策建議的可行性評估？
   B. 社會學想像（Mills）：個人困境是否連結至公共議題？
      是把結構問題個人化，還是把個人選擇結構化？
   C. 正常化機制（Foucault）：誰有權定義『正常』與『偏差』？
   D. 交織性：是否考慮階級/性別/種族/年齡等多重壓迫軸線的交疊？
   E. 全球—本土張力：概念是否具歐美中心性？
      是否以『現代化』為隱性標準評估非西方社會？

▌哲學視角補充維度：論證分析（僅哲學視角啟用時，於步驟2與步驟4間穿插）

   A. 論證重構（Argument Reconstruction）
      將文本核心論證重構為標準形式（前提P1, P2...→結論C）；
      區分主論證與子論證；標明推論步驟。
      追問：作者實際寫出的，與重構後最強的版本（principle of charity）
      之間有多大距離？

   B. 有效性與健全性（Validity & Soundness）
      推論形式是否有效？前提是否為真或可辯護？
      區分演繹（deductive）、歸納（inductive）、最佳解釋推論（abductive）；
      辨識論證類型錯置（如以歸納證據支撐演繹式全稱結論）。
      若分析對象為二階的詮釋性／評論性文本，其證成邏輯本屬詮釋學
      式（文本涵蓋度、部分—整體融貫、慷慨原則的邊界），不應直接
      套用演繹/歸納判準指控其『跳躍』或『謬誤』；應改為追問：這個
      詮釋性結論所需的證據強度，現有引文是否足以支撐，還是仍屬
      眾多可能讀法之一。

   C. 隱藏前提（Suppressed Premises）
      補足使論證有效所需的未言明前提（enthymeme 分析）。
      ——這是兩進路的交會點：隱藏前提往往正是第一層修辭格
      （以隱喻代替論證）與第四層意識形態（未經辯護的規範預設）
      的藏身處。

   D. 概念分析（Conceptual Analysis）
      關鍵概念是否給出必要/充分條件？定義是否前後一致？
      是否有歧義滑轉（equivocation）——同一詞在不同前提中意義偏移？
      關鍵區分（distinctions）是否成立（如事實/價值、分析/綜合）？

   E. 反例與思想實驗（Counterexamples & Thought Experiments）
      對全稱宣稱構造反例；檢視文本自身使用的思想實驗——
      其直覺泵（intuition pump）依賴哪些未明說的背景假設？
      思想實驗的設計本身可回饋到第一層修辭格分析
      （思想實驗即是一種論證性隱喻）。

   F. 兩進路的整合診斷
      微觀有效但宏觀可疑：論證形式無瑕，但前提的概念框架
      （修辭格層）或規範預設（意識形態層）承載了全部重量。
      宏觀融貫但微觀跳躍：體系有機自洽（有機主義），
      但關鍵推論步驟依賴隱喻滑轉而非邏輯連結。
      ——這兩種錯位是哲學文本最有價值的分析發現。

