【四元框架：通用定義 + 領域變體】
━━━━━━━━━━━━━━━━━━━━━━━━━━━

▌第一層：修辭格（Tropological Mode）
文本如何透過語言預構其對象。

- 隱喻（Metaphor）：主導喻象揭示思維模型
  文學：意象系統、象徵叢集｜史學：『歷史是鏡子』式類比
  哲學：柏拉圖『洞穴』、老子『水』｜社會學：『鐵牢籠』『場域』『液態現代性』
  ——概念命名預先框定分析對象的性質與可能的解決方案

- 換喻（Metonymy）：以部分代整體
  文學：以『紅樓』代貴族世界｜史學：以具體事件還原宏觀結構（年鑑學派）
  哲學：以『自由意志』代整個道德哲學
  社會學：以可測量指標替代複雜現實（GDP代福祉、學歷代人力資本）
  ——統計化約是最常見的換喻操作，追問：被化約掉的是什麼？

- 提喻（Synecdoche）：以個別代普遍
  文學：個別人物代表普遍命運｜史學：個別人物為時代象徵
  哲學：部分概念整合為普遍原則（黑格爾式綜合）
  社會學：特定群體經驗代表普遍現象（都市中產代『現代人』）
  ——追問：誰的局部被當成了整體？

- 反諷（Irony）：對自身建構的自覺距離
  文學：敘事者聲音與文本意義的裂縫｜史學：意識到敘述皆是建構
  哲學：體系的自我解構潛力｜社會學：研究者對知識宣稱的批判距離
  （如 Goffman 戲劇比喻——『都在演戲』則社會學家自己也在演）

▌第二層：情節模式（Emplotment Mode）
文本賦予其對象的『故事形狀』（參照 Frye 原型批評）。

- 浪漫（Romance）：克服逆境走向勝利/啟示
  文學：主角歷經考驗達成成長｜史學：民族/文明克服逆境的英雄敘事
  哲學：論證走向真理揭示或精神解放
  社會學：能動性大於結構制約（改革論、社會運動研究）

- 喜劇（Comedy）：衝突獲得整合，走向更高秩序
  文學：秩序重新整合（婚姻、和解收場）｜史學：危機終獲整合
  哲學：調解矛盾達成更高統一（黑格爾辯證法）
  社會學：制度或文化可協調利益競爭（功能主義、協商民主論）

- 悲劇（Tragedy）：結構性力量導致不可逆的失落或不可克服的困境
  文學：性格/命運/結構使主角走向失落｜史學：偉大文明因結構衝突毀滅
  哲學：認識限度或實踐兩難（康德二律背反）
  社會學：壓迫結構具再生產能力，只能在限制中尋找出路（批判理論、Bourdieu）

- 諷刺（Satire）：解構一切崇高性與知識宣稱
  文學：人物與社會皆缺乏崇高性｜史學：歷史進程無意義，人事受偶然擺布
  哲學：暴露一切體系的虛構性（懷疑主義）
  社會學：『客觀知識』本身是權力運作（Foucault、後結構主義）

▌第三層：論證模式（Formal Argument Mode）
文本的解釋邏輯與知識論立場。
（社會學版對應『結構—行動』與『量化—質性』兩組經典爭論）

- 形式主義（Formism）：個別性不可化約
  文學：個體能動性決定命運｜史學：Ranke 式個別事件獨特性
  哲學：概念精確定義，以清晰為目標
  社會學：詮釋社會學、民族誌（Weber 的 Verstehen、Geertz 深描）
  ——追問：是否承認脈絡的不可移植性？

- 有機主義（Organicism）：整體統攝個體
  文學：家族/階級/社會整體決定個人命運｜史學：民族精神、文明體系
  哲學：自足思想體系，各部分互相支撐
  社會學：功能主義、系統論（Durkheim、Parsons、Luhmann）
  ——追問：整體的『功能』由誰定義？誰的需求被視為系統需求？

- 機械主義（Mechanism）：普遍規律支配
  文學：外在力量決定人物走向｜史學：可重複的社會規律（馬克思史學）
  哲學：以因果法則解釋人類處境
  社會學：實證主義、量化研究（《自殺論》、計量社會學）
  ——追問：因果推論的前提是否充分？模型排除了哪些變項？

- 脈絡主義（Contextualism）：意義依賴特定時空情境
  文學：偶然交錯形塑命運｜史學：具體情境決定歷史走向
  哲學：問題無法超越歷史語境
  社會學：歷史社會學、文化社會學（Tilly、Bourdieu、Swidler）
  ——追問：跨脈絡比較的界限何在？

▌第四層：意識形態傾向（Ideological Implication）
文本預設或強化的政治/社會立場。

四種基本立場：
- 無政府主義：批判一切制度性規範的正當性，強調個體自主
- 保守主義：強調延續性，現有秩序/傳統為最可行形態
- 激進主義：強調結構性斷裂，主張根本轉型
- 自由主義：強調漸進改革與個人自由的擴展

各視角的特別警覺：
- 文學：作者位置性；誰有故事、誰是背景；文本的文化政治功能
- 史學：民族主義、殖民主義、帝國書寫的隱性意識形態；沉默的檔案
- 哲學：性別、種族與殖民預設常藏在『普遍性』主張之中
- 社會學：意識形態最易藏在『價值中立』的方法論宣稱背後，四項追問——
  ① 知識生產政治：誰的問題被視為『值得研究』？經費從何而來？
  ② 研究者位置性：階級/性別/種族/國籍如何影響對象的建構？
  ③ 代表性政治：研究對象如何被書寫？有機會回應嗎？
  ④ 政策含義鏈：結論在政策層次對誰有利？可能被誰挪用？

